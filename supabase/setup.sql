-- PiperTrace core case schema with owner-scoped RLS.
-- Intended for a fresh project. Safe to rerun for existing matching tables.

create table if not exists public.cases (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  category text not null check (category in ('image', 'document', 'video', 'audio')),
  title text not null,
  file_name text not null,
  mime_type text not null,
  size_bytes bigint not null check (size_bytes >= 0),
  sha256 text not null check (sha256 ~ '^[0-9a-f]{64}$'),
  storage_path text not null,
  reference_name text,
  reference_path text,
  reference_sha256 text check (reference_sha256 is null or reference_sha256 ~ '^[0-9a-f]{64}$'),
  findings jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists cases_user_created_idx
  on public.cases (user_id, created_at desc);

create index if not exists cases_user_category_idx
  on public.cases (user_id, category);

alter table public.cases enable row level security;

drop policy if exists "cases_select_own" on public.cases;
create policy "cases_select_own"
  on public.cases for select to authenticated
  using (user_id = (select auth.uid()));

drop policy if exists "cases_insert_own" on public.cases;
create policy "cases_insert_own"
  on public.cases for insert to authenticated
  with check (user_id = (select auth.uid()));

drop policy if exists "cases_update_own" on public.cases;
create policy "cases_update_own"
  on public.cases for update to authenticated
  using (user_id = (select auth.uid()))
  with check (user_id = (select auth.uid()));

drop policy if exists "cases_delete_own" on public.cases;
create policy "cases_delete_own"
  on public.cases for delete to authenticated
  using (user_id = (select auth.uid()));

create table if not exists public.audit_events (
  id bigint generated by default as identity primary key,
  case_id uuid not null references public.cases(id) on delete cascade,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  event text not null,
  detail jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists audit_events_case_created_idx
  on public.audit_events (case_id, created_at asc);

create index if not exists audit_events_user_created_idx
  on public.audit_events (user_id, created_at desc);

alter table public.audit_events enable row level security;

drop policy if exists "audit_events_select_own" on public.audit_events;
create policy "audit_events_select_own"
  on public.audit_events for select to authenticated
  using (
    user_id = (select auth.uid())
    and exists (
      select 1 from public.cases c
      where c.id = audit_events.case_id
        and c.user_id = (select auth.uid())
    )
  );

drop policy if exists "audit_events_insert_own" on public.audit_events;
create policy "audit_events_insert_own"
  on public.audit_events for insert to authenticated
  with check (
    user_id = (select auth.uid())
    and exists (
      select 1 from public.cases c
      where c.id = audit_events.case_id
        and c.user_id = (select auth.uid())
    )
  );

-- Audit rows may be appended and read by their owner; updates are intentionally not granted.
grant select, insert, update, delete on public.cases to authenticated;
grant select, insert on public.audit_events to authenticated;
grant usage, select on sequence public.audit_events_id_seq to authenticated;

-- PiperTrace private evidence storage hardening.
-- Safe to re-run: create/update the bucket and recreate only the named owner-scoped policies.

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'evidence',
  'evidence',
  false,
  52428800,
  array[
    'image/jpeg', 'image/png', 'image/webp',
    'video/mp4', 'video/quicktime', 'video/webm',
    'audio/wav', 'audio/x-wav', 'audio/mpeg', 'audio/mp4', 'audio/aac', 'audio/x-m4a'
  ]::text[]
)
on conflict (id) do update
set
  name = excluded.name,
  public = false,
  file_size_limit = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;

alter table storage.objects enable row level security;

drop policy if exists "evidence own read" on storage.objects;
create policy "evidence own read"
on storage.objects for select to authenticated
using (bucket_id = 'evidence' and (storage.foldername(name))[1] = auth.uid()::text);

drop policy if exists "evidence own write" on storage.objects;
create policy "evidence own write"
on storage.objects for insert to authenticated
with check (bucket_id = 'evidence' and (storage.foldername(name))[1] = auth.uid()::text);

drop policy if exists "evidence own delete" on storage.objects;
create policy "evidence own delete"
on storage.objects for delete to authenticated
using (bucket_id = 'evidence' and (storage.foldername(name))[1] = auth.uid()::text);
